using ApiTool.Backend.Data;
using ApiTool.Backend.Data.Entities;
using ApiTool.Backend.Results.Dashboard;
using ApiTool.Backend.Tests.TestInfrastructure;
using Microsoft.EntityFrameworkCore;

namespace ApiTool.Backend.Tests.Results.Dashboard;

/// <summary>
/// Latency benchmark tests for <c>GET /results/stats</c> and <c>GET /results/failures</c>
/// against a real Postgres database with a large dataset (behavior #7).
/// <para>
/// <b>These tests are skipped by default.</b> To run them, set the environment variable
/// <c>APITOOL_RUN_DASHBOARD_LATENCY_BENCH=1</c> and provide a Postgres connection string
/// via <c>DASHBOARD_BENCH_CONNECTION_STRING</c>.
/// </para>
/// <para>
/// Requirements verified:
/// <list type="bullet">
///   <item>Behavior #7: EXPLAIN ANALYZE shows the <c>(org_id, created_at)</c> index on
///     <c>results</c> is used for both the totals and trend queries.</item>
///   <item>Observed end-to-end query latency is below 800 ms on a 5 M-row fixture (allowed
///     regression threshold per task spec).</item>
/// </list>
/// </para>
/// <para>
/// Index expected: <c>IX_Results_OrgId_CreatedAt</c> on <c>results(org_id, created_at)</c>.
/// EF Core creates this from:
/// <code>e.HasIndex(x => new { x.OrgId, x.CreatedAt });</code>
/// in <see cref="AppDbContext.OnModelCreating"/>. Verify with:
/// <code>
/// EXPLAIN ANALYZE
///   SELECT COUNT(*) FROM results
///   WHERE org_id = '...' AND created_at >= now() - interval '30 days';
/// </code>
/// Expected plan node: <c>Index Scan using "IX_Results_OrgId_CreatedAt"</c>.
/// </para>
/// </summary>
public sealed class DashboardLatencyBenchTests
{
    private const string EnvVarEnable = "APITOOL_RUN_DASHBOARD_LATENCY_BENCH";
    private const string EnvVarConnStr = "DASHBOARD_BENCH_CONNECTION_STRING";
    private const long LatencyBudgetMs = 800;
    private const int SeedRowCount = 5_000_000;

    // ── stats latency ─────────────────────────────────────────────────────────

    /// <summary>
    /// Seeds 5 M result rows in Postgres and asserts that <c>GET /results/stats?window=30d</c>
    /// completes in under <see cref="LatencyBudgetMs"/> ms using the native Postgres SQL path.
    /// <para>
    /// Also verifies that EXPLAIN ANALYZE output contains a reference to the
    /// <c>(org_id, created_at)</c> index — confirming the query planner uses the index
    /// rather than a sequential scan.
    /// </para>
    /// </summary>
    [SkippableFact]
    public async Task Stats_latency_under_800ms_on_5M_rows_postgres()
    {
        Skip.IfNot(
            Environment.GetEnvironmentVariable(EnvVarEnable) == "1",
            $"Set {EnvVarEnable}=1 to run dashboard latency benchmarks.");

        var connStr = Environment.GetEnvironmentVariable(EnvVarConnStr)
            ?? throw new InvalidOperationException(
                $"Set {EnvVarConnStr} to a Postgres connection string before running latency benchmarks.");

        var opts = new DbContextOptionsBuilder<AppDbContext>()
            .UseNpgsql(connStr)
            .Options;

        await using var db = new AppDbContext(opts);
        await db.Database.MigrateAsync();

        var orgId  = await SeedBenchOrgAsync(db);
        var clock  = new FakeClock(DateTimeOffset.UtcNow);
        var svc    = new DashboardResultsService(db, clock);

        // ── EXPLAIN ANALYZE: verify index is used ─────────────────────────────
        // Use a parameterized command to match the project's convention (no interpolation).
        var explainOutput = await ExecuteExplainAsync(db, orgId);

        // The index name generated by EF Core from HasIndex(x => new { x.OrgId, x.CreatedAt })
        Assert.Contains("ix_results_org_id_created_at", explainOutput, StringComparison.OrdinalIgnoreCase);

        // ── latency assertion ─────────────────────────────────────────────────
        var sw = System.Diagnostics.Stopwatch.StartNew();
        var resp = await svc.GetStatsAsync(orgId, DashboardWindow.ThirtyDays, default);
        sw.Stop();

        Assert.True(
            sw.ElapsedMilliseconds < LatencyBudgetMs,
            $"GetStatsAsync latency {sw.ElapsedMilliseconds} ms exceeded budget of {LatencyBudgetMs} ms on {SeedRowCount:N0} rows.");

        Assert.True(resp.Totals.Runs > 0, "Expected seeded rows to be visible in the 30-day window.");
    }

    /// <summary>
    /// Seeds 5 M result items in Postgres and asserts that <c>GET /results/failures?window=7d</c>
    /// completes in under <see cref="LatencyBudgetMs"/> ms using the native Postgres SQL path.
    /// </summary>
    [SkippableFact]
    public async Task Failures_latency_under_800ms_on_5M_rows_postgres()
    {
        Skip.IfNot(
            Environment.GetEnvironmentVariable(EnvVarEnable) == "1",
            $"Set {EnvVarEnable}=1 to run dashboard latency benchmarks.");

        var connStr = Environment.GetEnvironmentVariable(EnvVarConnStr)
            ?? throw new InvalidOperationException(
                $"Set {EnvVarConnStr} to a Postgres connection string before running latency benchmarks.");

        var opts = new DbContextOptionsBuilder<AppDbContext>()
            .UseNpgsql(connStr)
            .Options;

        await using var db = new AppDbContext(opts);
        await db.Database.MigrateAsync();

        var orgId  = await SeedBenchOrgAsync(db);
        var clock  = new FakeClock(DateTimeOffset.UtcNow);
        var svc    = new DashboardResultsService(db, clock);

        var sw = System.Diagnostics.Stopwatch.StartNew();
        var resp = await svc.GetFailuresAsync(orgId, DashboardWindow.SevenDays, 10, default);
        sw.Stop();

        Assert.True(
            sw.ElapsedMilliseconds < LatencyBudgetMs,
            $"GetFailuresAsync latency {sw.ElapsedMilliseconds} ms exceeded budget of {LatencyBudgetMs} ms on {SeedRowCount:N0} rows.");

        // failures can be empty if no items were seeded in the 7d window — not an error
        Assert.NotNull(resp);
    }

    // ── helpers ───────────────────────────────────────────────────────────────

    /// <summary>
    /// Seeds a benchmark org with ~<see cref="SeedRowCount"/> result rows spread over 90 days,
    /// using bulk-insert batches of 10 000 to avoid timeout. Returns the seeded org id.
    /// </summary>
    private static async Task<Guid> SeedBenchOrgAsync(AppDbContext db)
    {
        const string BenchEmail = "bench-latency@dashboard.internal";
        const string BenchOrgSlug = "bench-latency-org";

        // Re-use existing bench org when the test is re-run against the same DB.
        var existing = await db.Organizations.FirstOrDefaultAsync(o => o.Slug == BenchOrgSlug);
        if (existing is not null)
            return existing.Id;

        var userId = Guid.NewGuid();
        db.Users.Add(new User { Id = userId, Email = BenchEmail, CreatedAt = DateTime.UtcNow });

        var orgId = Guid.NewGuid();
        db.Organizations.Add(new Organization
        {
            Id       = orgId,
            Name     = "Bench Latency Org",
            Slug     = BenchOrgSlug,
            OwnerId  = userId,
            Status   = OrgStatus.Active,
            CreatedAt = DateTime.UtcNow,
            UpdatedAt = DateTime.UtcNow,
        });
        await db.SaveChangesAsync();

        var rng   = new Random(42);
        var now   = DateTime.UtcNow;
        const int batchSize = 10_000;
        var totalBatches = SeedRowCount / batchSize;

        for (var b = 0; b < totalBatches; b++)
        {
            for (var i = 0; i < batchSize; i++)
            {
                var age      = TimeSpan.FromDays(rng.NextDouble() * 90);
                var passCount = rng.Next(0, 10);
                var failCount = rng.Next(0, 3);

                db.Results.Add(new Result
                {
                    Id             = Guid.NewGuid(),
                    OrgId          = orgId,
                    UploadedBy     = userId,
                    CollectionName = "bench",
                    RunAt          = now - age,
                    DurationMs     = rng.NextInt64(50, 5000),
                    PassCount      = passCount,
                    FailCount      = failCount,
                    SkippedCount   = 0,
                    CreatedAt      = now - age,
                });
            }
            await db.SaveChangesAsync();
        }

        return orgId;
    }

    /// <summary>
    /// Executes a parameterized <c>EXPLAIN ANALYZE</c> for the <c>results</c> table
    /// scoped to <paramref name="orgId"/> and returns the full planner output as a string.
    /// </summary>
    private static async Task<string> ExecuteExplainAsync(AppDbContext db, Guid orgId)
    {
        var conn = db.Database.GetDbConnection();
        if (conn.State != System.Data.ConnectionState.Open)
            await conn.OpenAsync();

        await using var cmd = conn.CreateCommand();
        cmd.CommandText = @"
            EXPLAIN ANALYZE
            SELECT COUNT(*)
            FROM results
            WHERE org_id = @orgId
              AND created_at >= now() - interval '30 days'
              AND created_at <= now();";

        var p = cmd.CreateParameter();
        p.ParameterName = "@orgId";
        p.Value = orgId;
        p.DbType = System.Data.DbType.Guid;
        cmd.Parameters.Add(p);

        var lines = new System.Text.StringBuilder();
        await using var reader = await cmd.ExecuteReaderAsync();
        while (await reader.ReadAsync())
            lines.AppendLine(reader.GetString(0));

        return lines.ToString();
    }
}
